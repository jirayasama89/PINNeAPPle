"""Phase 1 report: all models (seed mean ± 95 % t-interval, per band), and the pre-registered paired comparisons
R1 (B vs C), R2 (A, E vs B), R3 (each OS-FNO variant / CNN / DRO vs the best feature baseline of the task).
Holm correction over the tasks of each comparison family (McNemar p-values). Writes PHASE1_REPORT.md + results/phase1_comparisons.json.
usage: python phase1_report.py [dataset_tasks...]"""
import json
import sys

import numpy as np

from q1lib import BANDS, RESULTS
from stats_q1 import ci, compare, holm, load

TASKS = sys.argv[1:] or ["misalignment", "unbalance", "bearings", "all"]
NAMES = {"misalignment": "T1 misalignment", "unbalance": "T2 unbalance", "bearings": "T3 bearings", "all": "T4 all ten states",
         "comfaulda7": "C1 COMFAULDA"}
FEAT = ["rf", "mlp", "kan", "svm", "xgb"]
DEEP = ["osfno-A-nospeed", "osfno-B-head", "osfno-C-film", "osfno-E-phys", "cnn-spec", "osfno-B-dro", "osfno-B-supcon",
        "fno-trainonly", "osfno-B-noaug", "osfno-B-noprior", "osfno-B-commonaug"]


def summary(task, model):
    R = load("phase1", model, task)
    if len(R) < 5:
        return None
    f = np.array([r["pooled"]["macro_f1"] for r in R])
    b = {x: np.mean([v["macro_f1"] for r in R for n, v in r["per_split"].items() if f"_{x}_" in n]) for x in BANDS}
    return {"n": len(R), "mean": float(f.mean()), "ci": ci(f)[1], "bands": b, "worst": min(b.values())}


lines = ["# Phase 1 report (MAFAULDA, speed-tercile protocol Pb, 5 seeds, locked partitions)", "",
         "Generated by `phase1_report.py` from the result files listed in `HISTORY.jsonl`. Macro-F1 pooled over the three "
         "held-out terciles; low / mid / high = held-out tercile (low and high are extrapolation); worst = worst tercile. "
         "Paired tests on the same runs, partitions and seeds (PROTOCOL.md).", ""]
out = {"summaries": {}, "comparisons": {}}
for task in TASKS:
    lines += [f"## {NAMES[task]}", "", "| model | macro-F1 (mean ± 95 % CI) | low | mid | high | worst |", "|---|---|---|---|---|---|"]
    for m in FEAT + DEEP:
        s = summary(task, m)
        if s:
            out["summaries"][f"{task}/{m}"] = s
            lines.append(f"| {m} | {s['mean']:.3f} ± {s['ci']:.3f} | {s['bands']['low']:.3f} | {s['bands']['mid']:.3f} | "
                         f"{s['bands']['high']:.3f} | {s['worst']:.3f} |")
    lines.append("")

best_base = {t: max((m for m in FEAT if f"{t}/{m}" in out["summaries"]), key=lambda m: out["summaries"][f"{t}/{m}"]["mean"])
             for t in TASKS}
families = {"R1: B (speed in head) vs C (FiLM)": [("osfno-B-head", "osfno-C-film")],
            "R2: A (no speed) vs B": [("osfno-A-nospeed", "osfno-B-head")],
            "R2: E (physical speed) vs B": [("osfno-E-phys", "osfno-B-head")],
            "R2: E (physical speed) vs A": [("osfno-E-phys", "osfno-A-nospeed")]}
for m in ["osfno-A-nospeed", "osfno-B-head", "osfno-C-film", "osfno-E-phys", "cnn-spec", "osfno-B-dro"]:
    families[f"R3: {m} vs best feature baseline"] = [(m, None)]
for fam, pairs in families.items():
    rows = []
    for a, b in pairs:
        for t in TASKS:
            bb = b or best_base[t]
            if not (load("phase1", a, t) and len(load("phase1", a, t)) >= 5 and len(load("phase1", bb, t)) >= 5):
                continue
            r = compare("phase1", a, "phase1", bb, t, n_boot=2000)
            rows.append((t, a, bb, r))
    if not rows:
        continue
    padj = holm([r[3]["mcnemar"]["p"] for r in rows])
    lines += [f"## {fam}", "", "| task | A | B | diff (seed mean ± 95 % CI) | seeds A>B | low diff | mid diff | high diff | "
              "bootstrap 95 % (vote) | McNemar p (Holm) |", "|---|---|---|---|---|---|---|---|---|---|"]
    for (t, a, bb, r), pa in zip(rows, padj):
        d, h = r["diff_seed"]
        bd = {x: r["bands"][x]["diff"][0] for x in BANDS}
        lines.append(f"| {NAMES[t]} | {a} | {bb} | {d:+.3f} ± {h:.3f} | {r['n_seeds_positive']}/{len(r['seeds'])} | "
                     f"{bd['low']:+.3f} | {bd['mid']:+.3f} | {bd['high']:+.3f} | "
                     f"[{r['bootstrap_ci95'][0]:+.3f}, {r['bootstrap_ci95'][1]:+.3f}] | {r['mcnemar']['p']:.2g} ({pa:.2g}) |")
        out["comparisons"][f"{fam}|{t}"] = {**r, "mcnemar_p_holm": pa}
    lines.append("")
open(RESULTS.parent / "PHASE1_REPORT.md", "w").write("\n".join(lines) + "\n")
json.dump(out, open(RESULTS / "phase1_comparisons.json", "w"), indent=1, default=float)
print("\n".join(lines))
