"""Reproducibility ledger.

python history.py manifest <dataset>   -> results/data_manifest_<dataset>.json (every cached run: path, state, speed,
                                          tach_ok, SHA-1 of the raw CSV bytes, cache file and its SHA-256)
python history.py update               -> append one line per new/changed result file to HISTORY.jsonl
                                          (UTC time, file, SHA-256, task, model, seed, protocol, partition hash,
                                          pooled macro-F1, per-band macro-F1, code commit at registration),
                                          then regenerate SUMMARY.md (mean +- 95 % interval per task x model)
"""
from __future__ import annotations

import datetime as dt
import glob
import hashlib
import json
import os
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
RES = HERE / "results"
LEDGER = HERE / "HISTORY.jsonl"


def sha256(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for b in iter(lambda: f.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()


def git_head():
    try:
        return subprocess.check_output(["git", "rev-parse", "--short", "HEAD"], cwd=HERE, text=True).strip()
    except Exception:  # noqa: BLE001
        return "unknown"


def manifest(dataset):
    cache = os.environ.get("MAF_CACHE", "/home/user/data_raw/maf_cache") if dataset == "mafaulda" else \
        os.environ.get("COM_CACHE", "/home/user/data_raw/com_cache")
    out = []
    for f in sorted(glob.glob(os.path.join(cache, "*.npz"))):
        z = np.load(f, allow_pickle=True)
        rows = list(z["row"]) if "row" in z.files else list(z["rows"])
        fh = sha256(f)
        for r in rows:
            out.append({"path": r.get("path"), "state": r.get("state"), "speed_hz": r.get("speed_hz"),
                        "tach_ok": r.get("tach_ok"), "error": r.get("error"), "raw_csv_sha1": r.get("sha1"),
                        "cache_file": os.path.basename(f), "cache_sha256": fh})
    p = RES / f"data_manifest_{dataset}.json"
    json.dump({"dataset": dataset, "created_utc": dt.datetime.now(dt.UTC).replace(tzinfo=None).isoformat(timespec="seconds"),
               "n_runs": len(out), "runs": out}, open(p, "w"), indent=0)
    print(p, len(out), "runs")


def update():
    seen = {}
    if LEDGER.exists():
        for line in open(LEDGER):
            e = json.loads(line)
            seen[e["file"]] = e["sha256"]
    head = git_head()
    new = 0
    with open(LEDGER, "a") as led:
        for f in sorted(RES.glob("*/*/*/*_seed*.json")):
            rel = str(f.relative_to(HERE))
            h = sha256(f)
            if seen.get(rel) == h:
                continue
            r = json.load(open(f))
            bands = {k.split("_")[1]: round(v["macro_f1"], 4) for k, v in r["per_split"].items()}
            e = {"utc": dt.datetime.now(dt.UTC).replace(tzinfo=None).isoformat(timespec="seconds"), "file": rel, "sha256": h,
                 "experiment": f.parts[-4], "task": r["task"], "model": r["model"], "seed": r["seed"],
                 "protocol": r["protocol"], "dataset": r.get("dataset"), "partition_hash": r["partition_hash"],
                 "macro_f1": round(r["pooled"]["macro_f1"], 4), "balanced_accuracy": round(r["pooled"]["balanced_accuracy"], 4),
                 "bands": bands, "seconds": round(r.get("seconds_total", 0), 1), "code_commit_at_registration": head,
                 "status": "changed" if rel in seen else "new"}
            led.write(json.dumps(e) + "\n")
            new += 1
    summary()
    print("ledger:", new, "new/changed entries")
    return new


def summary():
    from scipy import stats
    latest = {}
    for line in open(LEDGER):
        e = json.loads(line)
        latest[e["file"]] = e
    g = defaultdict(list)
    for e in latest.values():
        g[(e["experiment"], e.get("dataset"), e["task"], e["model"], e["protocol"])].append(e)
    lines = ["# Summary of all result files (regenerated by `history.py update`; do not edit)", "",
             f"Updated {dt.datetime.now(dt.UTC).replace(tzinfo=None).isoformat(timespec='seconds')} UTC. Mean ± 95 % t-interval over seeds; "
             "bands = held-out speed tercile (low / mid / high), seed means. Source of truth: the JSON files listed in "
             "HISTORY.jsonl.", "",
             "| experiment | dataset | task | model | protocol | seeds | macro-F1 | low | mid | high | partition |",
             "|---|---|---|---|---|---|---|---|---|---|---|"]
    for k in sorted(g):
        es = g[k]
        v = np.array([e["macro_f1"] for e in es])
        h = stats.t.ppf(0.975, len(v) - 1) * v.std(ddof=1) / np.sqrt(len(v)) if len(v) > 1 else float("nan")
        b = {x: np.mean([e["bands"].get(x, np.nan) for e in es]) for x in ("low", "mid", "high")}
        ph = sorted({e["partition_hash"] for e in es})
        lines.append(f"| {k[0]} | {k[1]} | {k[2]} | {k[3]} | {k[4]} | {len(v)} | {v.mean():.3f} ± {h:.3f} | "
                     f"{b['low']:.2f} | {b['mid']:.2f} | {b['high']:.2f} | {','.join(ph)} |")
    open(HERE / "SUMMARY.md", "w").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    if sys.argv[1] == "manifest":
        manifest(sys.argv[2])
    else:
        update()
